"""Streamlit application for Titanic survival prediction."""

from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st

from src.init import MODEL_PATH
from src.predict import get_model_name, predict_survival


def main() -> None:
    """Create a professional web interface for the Titanic survival model."""
    st.set_page_config(page_title="Titanic Survival Prediction", page_icon="🚢", layout="wide")

    st.markdown(
        """
        <style>
            .stApp {
                background-image:
                    linear-gradient(rgba(7, 25, 47, 0.65), rgba(7, 25, 47, 0.72)),
                    url("https://images.unsplash.com/photo-1566072875009-8b0d0f32cad6?auto=format&fit=crop&w=1600&q=80");
                background-size: cover;
                background-position: center center;
                background-repeat: no-repeat;
                background-attachment: fixed;
                color: #f3f8ff;
            }
            .main .block-container {
                padding-top: 2rem;
                padding-bottom: 2rem;
            }
            h1 {
                color: #f8f5ee;
                font-weight: 900;
                letter-spacing: 0.04em;
                text-shadow: 0 2px 16px rgba(143, 194, 255, 0.3);
            }
            h2, h3, p, .stMarkdown {
                color: #edf6ff;
            }
            .stCaption {
                color: #cfe8ff;
                font-size: 1rem;
            }
            .stForm {
                background: rgba(11, 24, 39, 0.68);
                border: 1px solid rgba(181, 214, 255, 0.2);
                border-radius: 22px;
                padding: 1.4rem;
                box-shadow: 0 12px 30px rgba(0, 0, 0, 0.2);
            }
            .stButton > button {
                background: linear-gradient(90deg, #d9b36b 0%, #f0d49d 100%);
                color: #0a1e32;
                border: none;
                border-radius: 12px;
                padding: 0.72rem 1.4rem;
                font-weight: 800;
                width: 100%;
                box-shadow: 0 8px 20px rgba(217, 179, 107, 0.3);
            }
            .stButton > button:hover {
                background: linear-gradient(90deg, #e5c276 0%, #f8e6b1 100%);
            }
            [data-testid="stMetricValue"] {
                color: #f8f5ee;
                font-size: 2.1rem;
                font-weight: 800;
            }
            [data-testid="stMetricLabel"] {
                color: #d7ebff;
            }
            .stAlert, .stInfo, .stSuccess, .stWarning, .stError {
                border-radius: 14px;
            }
            .stInfo {
                background: rgba(8, 27, 45, 0.8);
                color: #edf6ff;
                border: 1px solid rgba(160, 206, 255, 0.3);
            }
            .stSuccess {
                background: rgba(29, 78, 58, 0.5);
                color: #ecfdf5;
                border: 1px solid rgba(110, 219, 170, 0.35);
            }
            .stError {
                background: rgba(127, 29, 29, 0.52);
                color: #fee2e2;
                border: 1px solid rgba(248, 113, 113, 0.35);
            }
            .metric-card {
                background: rgba(13, 25, 39, 0.75);
                border: 1px solid rgba(219, 228, 235, 0.18);
                border-radius: 18px;
                padding: 1rem;
                box-shadow: 0 10px 25px rgba(0, 0, 0, 0.15);
            }
            .stTextInput > div > div > input,
            .stSelectbox > div > div > div,
            .stNumberInput > div > div > input,
            .stSlider > div[data-baseweb="slider"] {
                background: rgba(16, 34, 52, 0.7);
                color: #f3f8ff;
                border: 1px solid rgba(179, 210, 255, 0.18);
                border-radius: 10px;
            }
            label {
                color: #eaf6ff !important;
            }
        </style>
        """,
        unsafe_allow_html=True,
    )

    st.title("🚢 Titanic Survival Prediction")
    st.caption("Shipboard survival estimator inspired by the Titanic era.")
    st.markdown(
        "This project uses passenger data to predict whether a person survived the Titanic disaster. "
        "The model is trained on the Titanic dataset and can estimate survival chances from basic booking and travel information."
    )

    st.subheader("Project Overview")
    st.write(
        "This application predicts survival using key factors such as passenger class, gender, age, family size, fare, and embarkation port. "
        "The prediction is generated by the trained machine learning model saved in the project folder."
    )

    with st.form("prediction_form"):
        st.subheader("Passenger Information")

        col1, col2 = st.columns(2)
        with col1:
            passenger_class = st.selectbox("Passenger Class", [1, 2, 3], index=0)
            sex = st.selectbox("Gender", ["male", "female"], index=0)
            age = st.slider("Age", min_value=0.0, max_value=100.0, value=30.0, step=1.0)
            siblings_spouses = st.number_input("Number of Siblings/Spouses", min_value=0, max_value=20, value=0)

        with col2:
            parents_children = st.number_input("Number of Parents/Children", min_value=0, max_value=20, value=0)
            fare = st.number_input("Fare", min_value=0.0, value=30.0, step=1.0)
            embarked = st.selectbox("Port of Embarkation", ["S", "C", "Q"], index=0)

        submit_button = st.form_submit_button("Predict Survival")

    if submit_button:
        try:
            prediction, probability = predict_survival(
                Pclass=passenger_class,
                Sex=sex,
                Age=age,
                SibSp=siblings_spouses,
                Parch=parents_children,
                Fare=fare,
                Embarked=embarked,
            )
        except FileNotFoundError:
            st.warning("Model file not found. Please run: python src/train_model.py")
            return
        except ValueError as exc:
            st.error(f"Input error: {exc}")
            return

        st.subheader("Prediction")
        st.markdown('<div class="metric-card">', unsafe_allow_html=True)
        if prediction == "Survived":
            st.success(f"Prediction: {prediction}")
        else:
            st.error(f"Prediction: {prediction}")

        st.metric("Survival Probability", f"{probability:.2f}%")
        st.markdown('</div>', unsafe_allow_html=True)

        st.subheader("Model Information")
        model_name = get_model_name(MODEL_PATH)
        st.info(f"Model used: {model_name}")


if __name__ == "__main__":
    main()
